$ErrorActionPreference = "Stop"

$repositoryRoot = Split-Path -Parent $PSScriptRoot
$webProject = Join-Path $repositoryRoot "src\Vezarati.Web"
$apiProject = Join-Path $repositoryRoot "src\Vezarati.Api\Vezarati.Api.csproj"
$publishFolder = Join-Path $repositoryRoot "www"
$staticOutput = Join-Path $webProject "dist"

if (-not (Test-Path $apiProject)) {
    throw "API project was not found: $apiProject"
}
if (-not (Test-Path (Join-Path $webProject "package.json"))) {
    throw "React project was not found: $webProject"
}

Push-Location $webProject
try {
    & npm ci
    if ($LASTEXITCODE -ne 0) { throw "npm ci failed with exit code $LASTEXITCODE." }

    & npm run build
    if ($LASTEXITCODE -ne 0) { throw "React build failed with exit code $LASTEXITCODE." }
}
finally {
    Pop-Location
}

if (-not (Test-Path $staticOutput)) {
    throw "React build output was not found: $staticOutput"
}

if (Test-Path $publishFolder) {
    Remove-Item $publishFolder -Recurse -Force
}

& dotnet publish $apiProject --configuration Release --output $publishFolder
if ($LASTEXITCODE -ne 0) { throw "dotnet publish failed with exit code $LASTEXITCODE." }

$wwwRoot = Join-Path $publishFolder "wwwroot"
New-Item -ItemType Directory -Path $wwwRoot -Force | Out-Null
Copy-Item -Path (Join-Path $staticOutput "*") -Destination $wwwRoot -Recurse -Force

Write-Host ""
Write-Host "IIS publish output: $publishFolder"
Write-Host "Set the IIS site's physical path to this folder and bind it to port 4000."
Write-Host "The ASP.NET Core Module web.config is generated by dotnet publish."
